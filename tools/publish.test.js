/* Tests for the content editor's publish endpoint, publish.gs.
 *
 * Loaded as plain JavaScript with fakes for UrlFetchApp, Utilities and the rest, like
 * booking-sweep.test.js. Covers what a mistake here would cost most: a content.js that
 * would undo newer prices, the token-expiry warning, and keeping personal data out of
 * commit messages in a public repository.
 *
 *   node tools/publish.test.js
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const src = fs.readFileSync(path.join(__dirname, 'publish.gs'), 'utf8');

function makeEnv(opts) {
  opts = opts || {};
  const props = Object.assign({ GITHUB_TOKEN: 'gh-test', FB_API_KEY: 'k', FB_EMAIL: 'clinic@example.com' }, opts.props || {});
  const calls = [];
  const headers = opts.expiry ? { 'GitHub-Authentication-Token-Expiration': opts.expiry } : {};
  const env = {
    PropertiesService: { getScriptProperties: () => ({ getProperty: k => (k in props ? props[k] : null) }) },
    Utilities: {
      base64Decode: s => Array.from(Buffer.from(s, 'base64')).map(b => (b > 127 ? b - 256 : b)),
      newBlob: bytes => ({ getDataAsString: () => Buffer.from(bytes.map(b => b & 255)).toString('utf8') }),
    },
    UrlFetchApp: { fetch: (url, o) => {
      calls.push({ url, method: o.method, payload: o.payload ? JSON.parse(o.payload) : null });
      let code = opts.httpCode || 200, body = {};
      if (/identitytoolkit/.test(url)) body = { users: [{ email: 'clinic@example.com' }] };
      else if (/git\/ref\/heads/.test(url)) body = { object: { sha: 'head000' } };
      else if (/git\/commits\/head000/.test(url)) body = { tree: { sha: 'tree000' } };
      else if (/git\/blobs/.test(url)) body = { sha: 'blob' + calls.length };
      else if (/git\/trees/.test(url)) body = { sha: 'tree111' };
      else if (/git\/commits$/.test(url)) body = { sha: 'abcdef1234567' };
      else if (/repos\/[^/]+\/[^/]+$/.test(url)) body = { permissions: { push: true } };
      if (/identitytoolkit/.test(url)) code = 200;
      return { getResponseCode: () => code, getContentText: () => JSON.stringify(body),
               getAllHeaders: () => headers };
    } },
    Logger: { log() {} },
  };
  const ctx = vm.createContext(env);
  vm.runInContext(src, ctx);
  return { ctx, calls };
}

let fail = 0;
const ok = (label, got, want) => {
  const pass = JSON.stringify(got) === JSON.stringify(want);
  if (!pass) fail++;
  console.log((pass ? '  PASS  ' : '  FAIL  ') + label +
    (pass ? '' : `\n          got  ${JSON.stringify(got)}\n          want ${JSON.stringify(want)}`));
};

/* content.js exactly as the editor writes it (contentFileText in admin-content.html) */
function editorFile(data) {
  const text = '/* Omega Dental — website content.\n   GENERATED by the admin content editor. */\n' +
               'window.OMEGA_CONTENT = ' + JSON.stringify(data, null, 2) + ';\n';
  return { path: 'assets/content.js', content: Buffer.from(text).toString('base64') };
}
const live = (() => { const s = { window: {} }; vm.runInNewContext(
  fs.readFileSync(path.join(__dirname, '../assets/content.js'), 'utf8'), s); return s.window.OMEGA_CONTENT; })();
const clone = o => JSON.parse(JSON.stringify(o));

console.log('--- what content.js may contain');
{
  const { ctx } = makeEnv();
  ok('the live price list in editor format is accepted', ctx._contentAllowed(editorFile(live)), '');
  const old = clone(live); old.prices.forEach(p => delete p.id);
  ok('a draft from before price ids is refused', /older copy of the price list/.test(ctx._contentAllowed(editorFile(old))), true);
  const dup = clone(live); dup.prices[1].id = dup.prices[0].id;
  ok('duplicate price ids are refused', /older copy/.test(ctx._contentAllowed(editorFile(dup))), true);
  const bad = clone(live); bad.prices[0].id = '<script>';
  ok('an id that is not a plain slug is refused', /older copy/.test(ctx._contentAllowed(editorFile(bad))), true);
  const code = { path: 'assets/content.js', content: Buffer.from('alert(1)').toString('base64') };
  ok('code in content.js is refused', ctx._contentAllowed(code), "content.js is not in the editor's format.");
  ok('a non-JPEG photo is refused', ctx._contentAllowed({ path: 'assets/services/x.jpg',
    content: Buffer.from('GIF89a').toString('base64') }), 'Not a JPEG photo: assets/services/x.jpg');
}

console.log('--- publishing');
{
  const { ctx, calls } = makeEnv();
  const out = ctx.publishContent({ idToken: 't', files: [editorFile(live)], message: 'Update website content' });
  ok('publish succeeds', [out.ok, out.commit], [true, 'abcdef1']);
  ok('no warning when GitHub reports no expiry', out.warning, undefined);
  const commit = calls.find(c => /git\/commits$/.test(c.url));
  ok('commit message carries no email address', /@/.test(commit.payload.message), false);
  ok('the branch moved is main', calls.some(c => c.method === 'patch' && /refs\/heads\/main$/.test(c.url)), true);
}
{
  const soon = new Date(Date.now() + 10 * 86400000).toISOString().slice(0, 19).replace('T', ' ') + ' UTC';
  const { ctx } = makeEnv({ expiry: soon });
  const out = ctx.publishContent({ idToken: 't', files: [editorFile(live)] });
  ok('token expiring in 10 days → warning in the reply', /expires on .* \(\d+ days\)/.test(out.warning || ''), true);
}
{
  const later = new Date(Date.now() + 90 * 86400000).toISOString().slice(0, 19).replace('T', ' ') + ' UTC';
  const { ctx } = makeEnv({ expiry: later });
  const out = ctx.publishContent({ idToken: 't', files: [editorFile(live)] });
  ok('token with 90 days left → no warning', out.warning, undefined);
}
{
  const { ctx } = makeEnv({ httpCode: 401 });
  const out = ctx.publishContent({ idToken: 't', files: [editorFile(live)] });
  ok('expired token → plain-language error', [out.ok, /expired or was revoked/.test(out.error)], [false, true]);
}
{
  const { ctx } = makeEnv({ expiry: '2027-01-05 08:00:00 UTC' });
  const report = ctx.checkPublishSetup();
  ok('checkPublishSetup reports access and the expiry date',
     /can write to/.test(report) && /Token expires: 2027-01-05/.test(report), true);
}

console.log(fail ? `\n${fail} FAILED` : '\nall passed');
process.exit(fail ? 1 : 0);
